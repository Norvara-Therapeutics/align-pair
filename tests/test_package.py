class TestWorkflows:
    def test_the_release_workflows_name_this_package(self) -> None:
        for name in ("prerelease.yml", "publish-pypi.yml"):
            text = (ROOT / ".github" / "workflows" / name).read_text(encoding="utf-8")
            assert "src/align_pair/__init__.py" in text
            assert "align_pair" in text
            assert "kmer_counter" not in text

    def test_the_publish_default_tag_is_this_version(self) -> None:
        """A tag default copied from a sibling checks out a tag that is not here."""
        text = (ROOT / ".github" / "workflows" / "publish-pypi.yml").read_text(
            encoding="utf-8"
        )
        assert f"default: v{align_pair.__version__}" in text

    def test_the_publisher_targets_this_distribution(self) -> None:
        text = (ROOT / ".github" / "workflows" / "publish-pypi.yml").read_text(
            encoding="utf-8"
        )
        assert "https://pypi.org/p/norvara-align-pair" in text
