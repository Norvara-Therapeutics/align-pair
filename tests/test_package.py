"""Release invariants, checked here so a build never discovers them.

A version that disagrees with itself, an export that does not import, a module
missing from the distribution: each of these passes a source-tree run and fails
for whoever installs the package.
"""

from __future__ import annotations

import ast
from pathlib import Path

import pytest

try:
    import tomllib
except ModuleNotFoundError:  # Python 3.10
    import tomli as tomllib

import align_pair

ROOT = Path(__file__).resolve().parent.parent
PACKAGE = ROOT / "src" / "align_pair"


def configured() -> dict:
    with (ROOT / "pyproject.toml").open("rb") as handle:
        return tomllib.load(handle)


class TestVersion:
    def test_the_two_version_literals_agree(self) -> None:
        """The tag, the metadata and the runtime all have to say one thing."""
        assert configured()["project"]["version"] == align_pair.__version__

    def test_the_version_is_a_prerelease_of_one_point_zero(self) -> None:
        assert align_pair.__version__ == "1.0.0rc4"


class TestExports:
    def test_every_exported_name_exists(self) -> None:
        missing = [name for name in align_pair.__all__ if not hasattr(align_pair, name)]
        assert missing == []

    def test_the_export_list_is_sorted_and_unique(self) -> None:
        assert align_pair.__all__ == sorted(set(align_pair.__all__))

    def test_the_entry_point_function_does_not_shadow_its_module(self) -> None:
        """``align`` the function and ``aligner`` the module are named apart.

        Binding the function as ``align_pair.align`` would shadow a module of
        that name, and every ``import align_pair.align`` elsewhere would then
        get the function. The module is therefore called ``aligner``.
        """
        import align_pair.aligner

        assert align_pair.aligner.__name__ == "align_pair.aligner"
        assert callable(align_pair.align)
        assert align_pair.align.__name__ == "align"
        assert align_pair.aligner.align is align_pair.align

    def test_no_submodule_is_shadowed_by_an_export(self) -> None:
        modules = {path.stem for path in PACKAGE.glob("*.py")} - {
            "__init__",
            "__main__",
        }
        shadowed = [name for name in align_pair.__all__ if name in modules]
        assert shadowed == []


