"""Generate ``src/align_pair/matrix_data.py`` from the NCBI matrix files.

The substitution matrices this package scores with are published by the NCBI
as part of the BLAST distribution. They are downloaded here rather than kept
in the repository, which is how EMBOSS and Biopython treat the same files, and
rewritten as a Python module so that an installed copy needs no data files and
no network.

    python scripts/build_matrices.py            # rewrite the module
    python scripts/build_matrices.py --check    # verify it still matches

Every matrix is checked before it is written: the row and column labels must
agree, the table must be symmetric, and the diagonal must be the largest entry
in its row for the unambiguous residues. A matrix that fails any of these is
named and nothing is written, because silence from a cross-check is not
agreement.
"""

from __future__ import annotations

import argparse
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TARGET = ROOT / "src" / "align_pair" / "matrix_data.py"

#: Where the files come from. One directory of the BLAST distribution.
SOURCE = "https://ftp.ncbi.nlm.nih.gov/blast/matrices/"

#: The matrices this package carries, as (file name, module name, kind).
WANTED: tuple[tuple[str, str, str], ...] = (
    ("BLOSUM45", "BLOSUM45", "protein"),
    ("BLOSUM50", "BLOSUM50", "protein"),
    ("BLOSUM62", "BLOSUM62", "protein"),
    ("BLOSUM80", "BLOSUM80", "protein"),
    ("PAM30", "PAM30", "protein"),
    ("PAM120", "PAM120", "protein"),
    ("PAM250", "PAM250", "protein"),
    ("NUC.4.4", "NUC.4.4", "nucleotide"),
)

#: NUC.4.2 is published beside NUC.4.4 and is deliberately not carried: its
#: table is 15 rows (the four bases and eleven ambiguity codes) against only
#: the four plain bases as columns, so it cannot score an ambiguity code
#: against another one, and a pair read the other way round would fall outside
#: the table. NUC.4.4 is the square form, and the one EMBOSS ships as EDNAFULL.

#: Residues whose diagonal entry must be the largest in its row. An ambiguity
#: code is deliberately excluded: NUC.4.4 scores S against S at -1, because two
#: independent draws from {C, G} agree only half the time.
UNAMBIGUOUS = {
    "protein": "ACDEFGHIKLMNPQRSTVWY",
    "nucleotide": "ACGTU",
}


def fetch(name: str) -> str:
    """Download one matrix file as text."""
    with urllib.request.urlopen(SOURCE + name, timeout=60) as response:
        return response.read().decode("ascii")


def parse(text: str, name: str) -> tuple[list[str], str, list[list[int]]]:
    """Read an NCBI matrix file into comments, labels and scores."""
    comments: list[str] = []
    labels = ""
    rows: list[list[int]] = []
    order: list[str] = []

    for line in text.splitlines():
        stripped = line.strip()
        if not stripped:
            continue
        if stripped.startswith("#"):
            comments.append(stripped.lstrip("#").strip())
            continue
        fields = stripped.split()
        if not labels:
            labels = "".join(fields)
            continue
        order.append(fields[0])
        rows.append([int(field) for field in fields[1:]])

    if not labels or not rows:
        raise ValueError(f"{name}: no score table found")
    if "".join(order) != labels:
        raise ValueError(
            f"{name}: row labels {''.join(order)} do not match columns {labels}"
        )
    for label, row in zip(order, rows):
        if len(row) != len(labels):
            raise ValueError(
                f"{name}: row {label} has {len(row)} scores for {len(labels)} columns"
            )
    return comments, labels, rows


def verify(name: str, kind: str, labels: str, rows: list[list[int]]) -> list[str]:
    """Return the reasons this matrix is not usable, empty when it is."""
    problems: list[str] = []
    for i, first in enumerate(labels):
        for j, second in enumerate(labels):
            if rows[i][j] != rows[j][i]:
                problems.append(
                    f"{name}: {first}/{second} is {rows[i][j]} but "
                    f"{second}/{first} is {rows[j][i]}"
                )
    for i, residue in enumerate(labels):
        if residue not in UNAMBIGUOUS[kind]:
            continue
        if rows[i][i] != max(rows[i]):
            problems.append(
                f"{name}: {residue} scores {rows[i][i]} against itself but "
                f"{max(rows[i])} against something else"
            )
    return problems


def render(tables: list[tuple[str, str, list[str], str, list[list[int]]]]) -> str:
    """Write the module text for the parsed matrices."""
    parts = [
        '"""The substitution matrices, as published by the NCBI.',
        "",
        "Generated by ``scripts/build_matrices.py`` from the files published at",
        f"<{SOURCE}>.",
        "Do not edit by hand: run the script, which downloads the originals,",
        "checks each table for symmetry and rewrites this module.",
        "",
        "Each entry carries the comment lines of its source file, so a matrix can",
        "say where it came from and at what scale its scores are expressed. A score",
        'in "1/2 bit units" is not comparable with one from a matrix in third-bit',
        "units, and a reader comparing two alignment scores needs to know that.",
        '"""',
        "",
        "from __future__ import annotations",
        "",
        "#: Where these tables were downloaded from.",
        f'SOURCE: str = "{SOURCE}"',
        "",
        "#: Matrix name to its source file's comment lines.",
        "COMMENTS: dict[str, tuple[str, ...]] = {",
    ]
    for name, _kind, comments, _labels, _rows in tables:
        parts.append(f'    "{name}": (')
        for comment in comments:
            parts.append(f"        {comment!r},")
        parts.append("    ),")
    parts.extend(
        [
            "}",
            "",
            "#: Matrix name to whether it scores nucleotide or protein residues.",
            "KINDS: dict[str, str] = {",
        ]
    )
    for name, kind, _comments, _labels, _rows in tables:
        parts.append(f'    "{name}": "{kind}",')
    parts.extend(
        [
            "}",
            "",
            "#: Matrix name to the residues its table is indexed by, in file order.",
            "LABELS: dict[str, str] = {",
        ]
    )
    for name, _kind, _comments, labels, _rows in tables:
        parts.append(f'    "{name}": "{labels}",')
    parts.extend(
        [
            "}",
            "",
            "#: Matrix name to its scores, as rows in the order of ``LABELS``.",
            "SCORES: dict[str, tuple[tuple[int, ...], ...]] = {",
        ]
    )
    for name, _kind, _comments, labels, rows in tables:
        parts.append(f'    "{name}": (')
        for row in rows:
            cells = ", ".join(f"{value:3d}" for value in row)
            parts.append(f"        ({cells}),")
        parts.append("    ),")
    parts.extend(["}", ""])
    return "\n".join(parts)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify the committed module matches the published files",
    )
    arguments = parser.parse_args(argv)

    tables = []
    problems: list[str] = []
    for filename, name, kind in WANTED:
        print(f"fetching {filename}", file=sys.stderr)
        comments, labels, rows = parse(fetch(filename), name)
        problems.extend(verify(name, kind, labels, rows))
        tables.append((name, kind, comments, labels, rows))

    if problems:
        print("matrices rejected:", file=sys.stderr)
        for problem in problems:
            print(f"  {problem}", file=sys.stderr)
        return 1

    text = render(tables)
    if arguments.check:
        current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
        if current != text:
            print(f"{TARGET} differs from the published files", file=sys.stderr)
            return 1
        print(f"{TARGET} matches the published files")
        return 0

    TARGET.write_text(text, encoding="utf-8")
    print(f"wrote {TARGET} with {len(tables)} matrices")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
